def build_layers() -> dict[str, Gerber]:
    layers = {
        "F_Cu": Gerber("front copper"),
        "B_Cu": Gerber("back copper"),
        "F_Mask": Gerber("front solder mask openings"),
        "B_Mask": Gerber("back solder mask openings"),
        "F_SilkS": Gerber("front silkscreen"),
        "Edge_Cuts": Gerber("board outline"),
    }

    layers["Edge_Cuts"].rect_outline(0.0, 0.0, BOARD_W, BOARD_H, 0.15)

    for pad in pads:
        if pad.kind == "npth":
            layers["F_SilkS"].circle_outline(pad.x, pad.y, 2.2, 0.12)
            continue

        for layer in (layers["F_Cu"], layers["B_Cu"]):
            if pad.shape == "square":
                layer.flash_rect(pad.x, pad.y, pad.pad, pad.pad)
            else:
                layer.flash_circle(pad.x, pad.y, pad.pad)
        for layer in (layers["F_Mask"], layers["B_Mask"]):
            if pad.shape == "square":
                layer.flash_rect(pad.x, pad.y, pad.pad + 0.20, pad.pad + 0.20)
            else:
                layer.flash_circle(pad.x, pad.y, pad.pad + 0.20)

    for r in routes:
        layers[r.layer].line(list(r.points), r.width)

    silk = layers["F_SilkS"]
    silk.rect_outline(14.0, 66.0, 46.0, 72.5, 0.12)
    draw_text(silk, "J1 ESP32-C6", 14.0, 76.8, 0.34)
