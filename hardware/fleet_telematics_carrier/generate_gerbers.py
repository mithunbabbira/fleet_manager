pads: list[Pad] = []
routes: list[Route] = []


def add_pad(ref: str, pin: str, name: str, net: str, x: float, y: float,
            drill: float = 0.90, pad: float = 1.80, shape: str = "circle",
            kind: str = "pth") -> None:
    pads.append(Pad(ref, pin, name, net, x, y, drill, pad, shape, kind))


def h_header(ref: str, x: float, y: float, pitch: float,
             pin_defs: list[tuple[str, str, str]], drill: float = 0.90,
             pad: float = 1.80) -> None:
    for i, (name, net, shape) in enumerate(pin_defs, start=1):
        add_pad(ref, str(i), name, net, x + (i - 1) * pitch, y, drill, pad, shape)


def v_header(ref: str, x: float, y: float, pitch: float,
             pin_defs: list[tuple[str, str, str]], drill: float = 0.90,
             pad: float = 1.80) -> None:
    for i, (name, net, shape) in enumerate(pin_defs, start=1):
        add_pad(ref, str(i), name, net, x, y - (i - 1) * pitch, drill, pad, shape)


def coord(ref: str, pin: str) -> tuple[float, float]:
    for pad in pads:
        if pad.ref == ref and pad.pin == pin:
            return pad.x, pad.y
    raise KeyError(f"{ref}.{pin}")


def route(layer: str, net: str, width: float, *pts: tuple[float, float]) -> None:
    routes.append(Route(layer, net, width, tuple(pts)))


