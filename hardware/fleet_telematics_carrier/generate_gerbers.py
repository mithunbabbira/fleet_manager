def route_segments(r: Route) -> list[tuple[tuple[float, float], tuple[float, float]]]:
    return list(zip(r.points, r.points[1:]))


def point_segment_distance(point: tuple[float, float], a: tuple[float, float],
                           b: tuple[float, float]) -> float:
    px, py = point
    ax, ay = a
    bx, by = b
    dx = bx - ax
    dy = by - ay
    if abs(dx) < 1e-9 and abs(dy) < 1e-9:
        return math.hypot(px - ax, py - ay)
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    x = ax + t * dx
    y = ay + t * dy
    return math.hypot(px - x, py - y)


def orientation(a: tuple[float, float], b: tuple[float, float],
                c: tuple[float, float]) -> float:
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


def on_segment(a: tuple[float, float], b: tuple[float, float],
               c: tuple[float, float]) -> bool:
    return (
        min(a[0], c[0]) - 1e-7 <= b[0] <= max(a[0], c[0]) + 1e-7 and
        min(a[1], c[1]) - 1e-7 <= b[1] <= max(a[1], c[1]) + 1e-7
    )


def segments_intersect(a: tuple[float, float], b: tuple[float, float],
                       c: tuple[float, float], d: tuple[float, float]) -> bool:
    o1 = orientation(a, b, c)
    o2 = orientation(a, b, d)
    o3 = orientation(c, d, a)
    o4 = orientation(c, d, b)
    if o1 * o2 < -1e-7 and o3 * o4 < -1e-7:
        return True
    if abs(o1) <= 1e-7 and on_segment(a, c, b):
        return True
    if abs(o2) <= 1e-7 and on_segment(a, d, b):
        return True
    if abs(o3) <= 1e-7 and on_segment(c, a, d):
        return True
    if abs(o4) <= 1e-7 and on_segment(c, b, d):
        return True
    return False


def sanity_check() -> None:
    for pad in pads:
        if not (0.0 <= pad.x <= BOARD_W and 0.0 <= pad.y <= BOARD_H):
            raise ValueError(f"{pad.ref}.{pad.pin} outside board")
    for r in routes:
        for x, y in r.points:
            if not (0.0 <= x <= BOARD_W and 0.0 <= y <= BOARD_H):
                raise ValueError(f"route {r.net} outside board at {(x, y)}")

    routed_layers = {"F_Cu", "B_Cu"}
    for idx, a_route in enumerate(routes):
        if a_route.layer not in routed_layers:
            continue
        for b_route in routes[idx + 1:]:
            if b_route.layer != a_route.layer or b_route.net == a_route.net:
                continue
            for a0, a1 in route_segments(a_route):
                for b0, b1 in route_segments(b_route):
                    if segments_intersect(a0, a1, b0, b1):
                        raise ValueError(
                            f"{a_route.layer}: {a_route.net} crosses {b_route.net} "
                            f"between {a0}->{a1} and {b0}->{b1}"
                        )

    for r in routes:
        if r.layer not in routed_layers:
            continue
        for pad in pads:
            if pad.kind != "pth" or pad.net == r.net:
                continue
            keepout = pad.pad / 2.0 + r.width / 2.0 + 0.12
            for a, b in route_segments(r):
                if point_segment_distance((pad.x, pad.y), a, b) < keepout:
                    raise ValueError(
                        f"{r.layer}: route {r.net} too close to {pad.ref}.{pad.pin} "
                        f"({pad.net})"
                    )


def main() -> None:
    sanity_check()
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    layers = build_layers()
    for name, layer in layers.items():
        (OUT / f"fleet_telematics_carrier-{name}.gbr").write_text(layer.render(), encoding="utf-8")
    write_drill(OUT / "fleet_telematics_carrier-PTH.drl", npth=False)
    write_drill(OUT / "fleet_telematics_carrier-NPTH.drl", npth=True)
    write_csvs()

    if ZIP_PATH.exists():
        ZIP_PATH.unlink()
    with ZipFile(ZIP_PATH, "w", compression=ZIP_DEFLATED) as zf:
        for file in sorted(OUT.iterdir()):
            zf.write(file, arcname=file.name)

    print(f"Wrote {OUT}")
    print(f"Wrote {ZIP_PATH}")


if __name__ == "__main__":
    main()
