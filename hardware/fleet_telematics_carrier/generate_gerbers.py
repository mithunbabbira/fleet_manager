def draw_text(g: Gerber, text: str, x: float, y: float, scale: float = 0.32) -> None:
    cx = x
    cy = y
    dot = scale * 0.72
    for ch in text.upper():
        if ch == "\n":
            cy -= scale * 9
            cx = x
            continue
        pattern = FONT.get(ch, FONT[" "])
        for row, bits in enumerate(pattern):
            for col, bit in enumerate(bits):
                if bit == "1":
                    g.flash_rect(cx + col * scale, cy - row * scale, dot, dot)
        cx += scale * 6


