def write_drill(path: Path, npth: bool) -> None:
    selected = [p for p in pads if (p.kind == "npth") == npth]
    groups: dict[float, list[Pad]] = {}
    for pad in selected:
        groups.setdefault(pad.drill, []).append(pad)

    lines = [
        "M48",
        f"; {path.name}",
        "METRIC,LZ",
    ]
    for idx, drill in enumerate(sorted(groups), start=1):
        lines.append(f"T{idx:02d}C{drill:.3f}")
    lines.extend(["%", "G90", "M71"])
    for idx, drill in enumerate(sorted(groups), start=1):
        lines.append(f"T{idx:02d}")
        for pad in groups[drill]:
            lines.append(f"X{pad.x:.3f}Y{pad.y:.3f}")
    lines.append("M30")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_csvs() -> None:
    with (OUT / "bom.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["ref", "value", "notes"])
        for comp in components:
            writer.writerow([comp.ref, comp.value, comp.notes])

    with (OUT / "netlist.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["ref", "pin", "pin_name", "net", "x_mm", "y_mm"])
