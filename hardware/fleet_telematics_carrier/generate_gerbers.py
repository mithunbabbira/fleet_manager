class Gerber:
    def __init__(self, name: str) -> None:
        self.name = name
        self.apertures: dict[str, int] = {}
        self.commands: list[str] = []

    def aperture(self, spec: str) -> int:
        if spec not in self.apertures:
            self.apertures[spec] = 10 + len(self.apertures)
        return self.apertures[spec]

    def select(self, code: int) -> None:
        self.commands.append(f"D{code}*")

    def flash_circle(self, x: float, y: float, diameter: float) -> None:
        code = self.aperture(f"C,{diameter:.3f}")
        self.select(code)
        self.commands.append(f"{xy(x, y)}D03*")

    def flash_rect(self, x: float, y: float, w: float, h: float) -> None:
        code = self.aperture(f"R,{w:.3f}X{h:.3f}")
        self.select(code)
        self.commands.append(f"{xy(x, y)}D03*")

    def line(self, points: list[tuple[float, float]], width: float) -> None:
        if len(points) < 2:
            return
        code = self.aperture(f"C,{width:.3f}")
        self.select(code)
        self.commands.append(f"{xy(*points[0])}D02*")
        for point in points[1:]:
            self.commands.append(f"{xy(*point)}D01*")

    def rect_outline(self, x0: float, y0: float, x1: float, y1: float, width: float) -> None:
        self.line([(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)], width)

    def circle_outline(self, x: float, y: float, radius: float, width: float, segments: int = 48) -> None:
        pts = []
        for i in range(segments + 1):
            a = 2.0 * math.pi * i / segments
            pts.append((x + radius * math.cos(a), y + radius * math.sin(a)))
        self.line(pts, width)

    def render(self) -> str:
        lines = [
            f"G04 {self.name} generated by generate_gerbers.py*",
            "%FSLAX46Y46*%",
            "%MOMM*%",
            "%LPD*%",
            "G75*",
        ]
        for spec, code in sorted(self.apertures.items(), key=lambda item: item[1]):
            lines.append(f"%ADD{code}{spec}*%")
        lines.extend(self.commands)
        lines.append("M02*")
        return "\n".join(lines) + "\n"


def xy(x: float, y: float) -> str:
    return f"X{int(round(x * 1_000_000)):010d}Y{int(round(y * 1_000_000)):010d}"


